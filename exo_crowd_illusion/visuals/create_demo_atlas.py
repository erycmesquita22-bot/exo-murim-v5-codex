#!/usr/bin/env python3
"""Create fully original, simple vanilla 64x64 voxel skin tiles for CROWD demo.
Generated by procedural drawing: no external Minecraft skins or protected media.
"""
from pathlib import Path
from PIL import Image,ImageDraw
import colorsys,random
root=Path(__file__).resolve().parents[1]
atlas=Image.new('RGBA',(512,512),(0,0,0,0))

PARTS=[('head',(0,0),8,8,8),('body',(16,16),8,12,4),('arm_r',(40,16),4,12,4),('arm_l',(32,48),4,12,4),('leg_r',(0,16),4,12,4),('leg_l',(16,48),4,12,4)]

def color(h,s,v):
    return tuple(int(x*255) for x in colorsys.hsv_to_rgb(h,s,v))+(255,)

def paint_skin(idx):
    rnd=random.Random(1000+idx)
    im=Image.new('RGBA',(64,64),(0,0,0,0))
    d=ImageDraw.Draw(im)
    tone=rnd.choice([(240,192,143,255),(211,153,105,255),(174,121,81,255),(128,86,63,255),(244,207,161,255)])
    outfit=color((idx*0.137)%1,0.47+rnd.random()*0.3,0.36+rnd.random()*0.25)
    outfit_dark=tuple(max(0,int(v*0.67)) for v in outfit[:3])+(255,)
    pants=color((idx*0.097+0.52)%1,0.28,0.30)
    hair=rnd.choice([(24,21,20,255),(65,41,25,255),(111,72,39,255),(50,55,50,255)])
    for name,(u,v),w,h,depth in PARTS:
        base = tone if name=='head' else outfit if name in ('body','arm_r','arm_l') else pants
        d.rectangle((u,v+depth,u+depth-1,v+depth+h-1),fill=base)
        d.rectangle((u+depth,v+depth,u+depth+w-1,v+depth+h-1),fill=base)
        d.rectangle((u+depth+w,v+depth,u+depth+w+depth-1,v+depth+h-1),fill=base)
        d.rectangle((u+depth+w+depth,v+depth,u+depth+2*w+depth-1,v+depth+h-1),fill=base)
        d.rectangle((u+depth,v,u+depth+w-1,v+depth-1),fill=base)
        d.rectangle((u+depth+w,v,u+depth+2*w-1,v+depth-1),fill=base)
        if name == 'head':
            d.rectangle((u,v+depth,u+3,v+depth+3),fill=hair)
            d.rectangle((u+depth,v+depth,u+depth+7,v+depth+1),fill=hair)
            d.rectangle((u+depth,v,u+depth+7,v+4),fill=hair)
            for eye in [u+depth+2,u+depth+5]:
                d.rectangle((eye,v+depth+4,eye,v+depth+4),fill=(20,22,25,255))
        if name == 'body':
            d.line((u+depth+3,v+depth,u+depth+3,v+depth+h-3),fill=outfit_dark,width=1)
            d.rectangle((u+depth,v+depth+h-3,u+depth+w-1,v+depth+h-2),fill=outfit_dark)
            d.rectangle((u+depth+3,v+depth+h-3,u+depth+4,v+depth+h-2),fill=(202,171,92,255))
        if name in ('arm_r','arm_l'):
            d.rectangle((u+depth,v+depth+h-2,u+depth+w-1,v+depth+h-1),fill=outfit_dark)
        if name.startswith('leg'):
            d.rectangle((u+depth,v+depth+h-2,u+depth+w-1,v+depth+h-1),fill=(48,35,28,255))
    return im

for i in range(64):
    item=paint_skin(i)
    atlas.paste(item,((i%8)*64,(i//8)*64))
target=root/'assets'/'skins_demo_atlas.png'
atlas.save(target,optimize=True)
print(target)
